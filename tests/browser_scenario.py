"""Run inside the browser-test image against the isolated simulation server."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = os.environ['TEST_URL']
artifacts = Path('/artifacts')
artifacts.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(args=['--disable-dev-shm-usage'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1000})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(url)
    expect(page.get_by_role('heading', name='Welcome to Recorder.')).to_be_visible()
    page.get_by_label('Access token').fill('wrong-token')
    page.get_by_role('button', name='Open my library').click()
    expect(page.locator('#login-error')).to_contain_text('not recognised')
    page.get_by_label('Access token').fill(os.environ['TEST_TOKEN'])
    page.get_by_role('button', name='Open my library').click()
    expect(page.get_by_role('heading', name='Your next favourite starts here.')).to_be_visible()
    page.locator('#refresh').click()
    expect(page.get_by_role('heading', name='The Quiet Coast')).to_be_visible(timeout=20000)
    page.screenshot(path=str(artifacts / 'desktop.png'), full_page=True)
    page.get_by_label('Search programmes', exact=True).fill('quiet coast')
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.locator('.programme-card')).to_have_count(1)
    page.get_by_role('button', name='Add to queue').click()
    page.locator('[data-view=queue]').click()
    expect(page.locator('.job').filter(has_text='The Quiet Coast').locator('.state')).to_have_text('Completed', timeout=20000)
    page.locator('[data-view=history]').click()
    expect(page.get_by_role('heading', name='Simulated recording b0000002')).to_be_visible()
    page.locator('[data-view=search]').click()
    page.locator('summary').click()
    page.get_by_label('BBC episode link or programme ID').fill('b0000001')
    page.locator('#pid-form').get_by_role('button', name='Add to queue').click()
    slow = page.locator('.job').filter(has=page.get_by_role('heading', name='b0000001', exact=True))
    expect(slow.locator('.state')).to_have_text('Running', timeout=20000)
    expect(slow.locator('progress')).to_have_attribute('value', '12.5', timeout=15000)
    slow.get_by_role('button', name='View log').click()
    expect(page.locator('#log-output')).to_contain_text('12.5%')
    page.get_by_role('button', name='Close log').click()
    slow.get_by_role('button', name='Cancel', exact=True).click()
    expect(slow.locator('.state')).to_have_text('Cancelled', timeout=15000)
    page.locator('[data-view=search]').click()
    page.get_by_label('BBC episode link or programme ID').fill('b0000003')
    page.locator('#pid-form').get_by_role('button', name='Add to queue').click()
    failed = page.locator('.job').filter(has=page.get_by_role('heading', name='b0000003', exact=True))
    expect(failed.locator('.state')).to_have_text('Failed', timeout=20000)
    expect(failed.get_by_role('button', name='Retry')).to_be_visible()
    failed.get_by_role('button', name='View log').click()
    expect(page.locator('#log-output')).to_contain_text('Simulated BBC connection failure')
    page.get_by_role('button', name='Close log').click()
    page.locator('[data-view=pvr]').click()
    expect(page.get_by_role('heading', name='Existing search')).to_be_visible()
    page.get_by_role('button', name='Run saved searches').click()
    expect(page.locator('#notice')).to_contain_text('queue')
    page.set_viewport_size({'width': 390, 'height': 844})
    page.locator('[data-view=search]').click()
    page.get_by_label('Search programmes', exact=True).fill('')
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.get_by_role('heading', name='Late Night Notes')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile layout overflows'
    page.screenshot(path=str(artifacts / 'mobile.png'), full_page=True)
    page.set_viewport_size({'width': 1440, 'height': 1000})
    page.get_by_role('button', name='Sign out').click()
    expect(page.get_by_role('heading', name='Welcome to Recorder.')).to_be_visible()
    assert not errors, errors
    browser.close()
print('PASS BROWSER SIMULATION: login/errors, empty state, refresh/search, download/history, live progress/logs, cancellation/failure, PVR, desktop/mobile layout, logout; no JavaScript errors')
